// Regenerate cordis.patch.yml from the agent-preset declarations shipped by a
// local DeepSeek Harness installation.
//
// Why this exists: a DSH patch replaces a targeted row *wholesale*. The only
// supported way to change one nested value (the threshold of the
// `compaction-basic` row inside a preset declaration) is to restate the whole
// preset declaration. That copy would otherwise rot silently whenever DSH
// updates a preset, so keep it generated and re-run this after upgrading DSH.
//
// Usage:
//   node tools/regen-preset-overrides.mjs [--presets-dir <dir>] [--check]
//
// Resolution order for the presets directory:
//   1. --presets-dir <dir>
//   2. $DSH_PRESETS_DIR
//   3. <candidate node_modules>/@deepseek-ai/dsh-web-app/presets
//      candidates: cwd (walking up), $DSH_HOME/profiles/*/node_modules,
//                  $DSH_INSTALL/node_modules, $DSH_APP_DIR/node_modules
//
// `--check` writes nothing and exits non-zero when the committed file is stale.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { createRequire } from 'node:module';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(ROOT, 'cordis.patch.yml');
const PRESETS = ['standard', 'cordis', 'ptc'];
const PLUGIN_NAME = 'dsh-plugin-auto-compact';
/** The one value this plugin exists to change. */
const COMPACT_CONFIG = 'auto: true\nthresholdRatio: 0.5\nretainRatio: 0.16\nheadroomTokens: 65536\n';

const args = process.argv.slice(2);
const argOf = (flag) => {
  const i = args.indexOf(flag);
  return i === -1 ? undefined : args[i + 1];
};
const checkOnly = args.includes('--check');

/** Load `yaml` from the plugin, the invocation base, or a DSH installation. */
function loadYaml() {
  const bases = [
    import.meta.url,
    join(ROOT, 'package.json'),
    ...candidateNodeModules().map((dir) => join(dir, 'noop.js')),
  ];
  for (const base of bases) {
    try {
      return createRequire(base)('yaml');
    } catch { /* try the next base */ }
  }
  throw new Error('cannot load the "yaml" package — run `npm install` here, or point $DSH_HOME at a DSH installation');
}

function candidateNodeModules() {
  const dirs = [];
  for (let dir = process.cwd(); ; ) {
    dirs.push(join(dir, 'node_modules'));
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  const home = process.env.DSH_HOME ?? join(homedir(), '.dsh');
  const profiles = join(home, 'profiles');
  dirs.push(join(profiles, 'node_modules'));
  if (existsSync(profiles)) {
    for (const entry of readdirSync(profiles, { withFileTypes: true })) {
      if (entry.isDirectory()) dirs.push(join(profiles, entry.name, 'node_modules'));
    }
  }
  dirs.push(join(home, 'node_modules'));
  for (const env of ['DSH_INSTALL', 'DSH_APP_DIR', 'DSH_HARNESS_DIR']) {
    if (process.env[env]) dirs.push(join(process.env[env], 'node_modules'));
  }
  return dirs;
}

function findPresetsDir() {
  const explicit = argOf('--presets-dir') ?? process.env.DSH_PRESETS_DIR;
  if (explicit !== undefined) {
    const dir = resolve(explicit);
    if (!existsSync(dir)) throw new Error(`presets directory not found: ${dir}`);
    return dir;
  }
  const tried = [];
  for (const modules of candidateNodeModules()) {
    const direct = join(modules, '@deepseek-ai', 'dsh-web-app', 'presets');
    tried.push(direct);
    if (existsSync(direct)) return direct;
  }
  throw new Error(`cannot locate @deepseek-ai/dsh-web-app/presets; pass --presets-dir or set $DSH_PRESETS_DIR\nsearched:\n  ${tried.join('\n  ')}`);
}

const yaml = loadYaml();
const { parseDocument, Document, YAMLSeq } = yaml;
const presetsDir = findPresetsDir();
const compactConfigNode = () => parseDocument(COMPACT_CONFIG).contents;

/** Restate one shipped preset declaration with its compaction threshold changed. */
function presetOverride(preset) {
  const file = join(presetsDir, `${preset}.patch.yml`);
  const doc = parseDocument(readFileSync(file, 'utf8'));
  const row = doc.contents.items[0].get('insert').items[0];
  if (row.get('id') !== `preset-${preset}`) {
    throw new Error(`${file}: expected row id preset-${preset}, found ${row.get('id')}`);
  }
  const basic = row.getIn(['config', 'plugins']).items.find((it) => it.get('id') === 'compaction')
    .get('config').items.find((it) => it.get('id') === 'compaction-basic');
  if (!basic) throw new Error(`${file}: the preset declares no compaction-basic row`);
  basic.set('config', compactConfigNode());
  const out = new Document();
  out.contents = new YAMLSeq();
  out.contents.items.push(row);
  return out.toString().replace(/\n$/, '\n');
}

const HEADER = `# dsh-plugin-auto-compact — generated by tools/regen-preset-overrides.mjs, do not edit by hand.
#
# Generated file / 由脚本生成，请勿手改. Five rows are contributed:
#   1. auto-compact      the plugin's own host row (logs the effective threshold)
#   2. compaction-basic  enables the host-plane engine and drops 0.8 -> 0.5
#   3-5. preset-standard / preset-cordis / preset-ptc
#                        the same change inside each session preset, because a
#                        preset mounts its own isolated compaction engine
#
# A DSH patch replaces a targeted row wholesale, so rows 3-5 restate the whole
# preset declaration; they are copies of @deepseek-ai/dsh-web-app/presets/*
# (MIT). Re-run this script after upgrading DSH: npm run regen
`;

let out = `${HEADER}- insert:
    - id: auto-compact
      name: ${PLUGIN_NAME}
- id: compaction-basic
  name: '@deepseek-ai/dsh-compaction-basic'
  disabled: false
  config:
${COMPACT_CONFIG.split('\n').filter(Boolean).map((line) => `    ${line}`).join('\n')}
`;
for (const preset of PRESETS) {
  out += `# ── preset: ${preset} (full declaration, threshold changed) ─────────────────\n${presetOverride(preset)}`;
}

const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
if (checkOnly) {
  if (current !== out) {
    console.error('cordis.patch.yml is stale — run: npm run regen');
    process.exit(1);
  }
  console.log('cordis.patch.yml is up to date');
} else {
  writeFileSync(TARGET, out);
  console.log(`wrote ${TARGET}`);
}
console.log(`presets read from: ${presetsDir}`);
console.log(`rows: auto-compact, compaction-basic, ${PRESETS.map((p) => `preset-${p}`).join(', ')}`);
console.log(`thresholdRatio 0.5 occurrences: ${out.split('thresholdRatio: 0.5').length - 1}`);
